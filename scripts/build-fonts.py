#!/usr/bin/env python3
"""Subset JetBrains Mono Nerd Font into small woff2 files and write them to src/fonts.ts.

SVGs shown through <img> can't load external fonts, but data: URIs in @font-face work,
so the cards embed a subset with Latin text, box drawing and a handful of icons.

Usage: python3 scripts/build-fonts.py [font-dir]
JetBrains Mono is licensed under the SIL Open Font License 1.1, embedding is allowed.
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

FONT_DIR = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF")
OUT = Path(__file__).resolve().parent.parent / "src" / "fonts.ts"

WEIGHTS = {
    "regular": "JetBrainsMonoNerdFontMono-Regular.ttf",
    "bold": "JetBrainsMonoNerdFontMono-Bold.ttf",
}

# icon name in code -> glyph name in the Nerd Font
ICONS = {
    "star": "oct-star",
    "commit": "oct-git_commit",
    "pr": "oct-git_pull_request",
    "repo": "oct-repo",
    "flame": "oct-flame",
    "trophy": "fa-trophy",
    "forked": "oct-repo_forked",
    "github": "oct-mark_github",
    "calendar": "fa-calendar_days",
    "arch": "linux-archlinux",
    "code": "oct-code",
    "pillLeft": "ple-left_half_circle_thick",
    "pillRight": "ple-right_half_circle_thick",
}

RANGES = [
    (0x20, 0x7E),      # ASCII
    (0xA0, 0x17F),     # Latin-1 + Latin Extended-A (Czech and friends)
    (0x2010, 0x2027),  # dashes, quotes, bullet, ellipsis
    (0x2500, 0x259F),  # box drawing + blocks
    (0x25A0, 0x25FF),  # geometric shapes
    (0x276F, 0x276F),  # ❯
]


def resolve_icons(path: Path) -> dict[str, int]:
    font = TTFont(path)
    by_glyph = {glyph: cp for cp, glyph in font.getBestCmap().items()}
    missing = [g for g in ICONS.values() if g not in by_glyph]
    if missing:
        sys.exit(f"glyphs not found: {missing}")
    return {name: by_glyph[glyph] for name, glyph in ICONS.items()}


def build(path: Path, codepoints: list[int]) -> str:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []  # no ligatures, keep it a plain monospace grid
    options.name_IDs = []
    options.notdef_outline = True
    font = subset.load_font(str(path), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    buf = io.BytesIO()
    subset.save_font(font, buf, options)
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    icons = resolve_icons(FONT_DIR / WEIGHTS["regular"])
    codepoints = [cp for lo, hi in RANGES for cp in range(lo, hi + 1)] + list(icons.values())

    lines = [
        "// Generated by scripts/build-fonts.py, do not edit by hand.",
        "// JetBrains Mono Nerd Font subset, SIL Open Font License 1.1.",
        "",
    ]
    for weight, file in WEIGHTS.items():
        data = build(FONT_DIR / file, codepoints)
        lines.append(f'export const {weight} = "{data}";')
        print(f"{weight}: {len(data) / 1024:.1f} KiB base64")

    lines += ["", "export const icons = {"]
    lines += [f'  {name}: "\\u{{{cp:x}}}",' for name, cp in icons.items()]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
